/**
 * 이름 하나를 뽑는다 — **실존 인물과 이미 쓴 이름을 피한다.**
 * 다 막히는 경우를 대비해 횟수를 제한하고, 그때는 거른 뒤 아무거나 돌려준다.
 */
export function makeName(
  rng: RNG,
  given: string[] = GIVEN_YOUNG,
  surnames: string[] = SURNAMES,
  taken?: Set<string>,
): string {
  for (let i = 0; i < 40; i++) {
    const n = surnames[rng.int(0, surnames.length - 1)] + given[rng.int(0, given.length - 1)];
    if (BLOCKED.has(n)) continue;
    if (taken?.has(n)) continue;
    taken?.add(n);
    return n;
  }
  // 여기까지 오면 거의 다 막힌 것 — 적어도 실존 인물은 피한다
  const rest = surnames.flatMap((s) => given.map((g) => s + g)).filter((n) => !BLOCKED.has(n));
  const n = rest[rng.int(0, rest.length - 1)];
  taken?.add(n);
  return n;
}
